function getT() {
  if (typeof window === "undefined") return PT;
  try {
    var cfg = JSON.parse(localStorage.getItem("cenffor_config") || "{}");
    if (cfg.sistema && cfg.sistema.idioma === "English") return EN;
  } catch (e) {}
  return PT;
}

